CREATE TABLE venue (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    address    VARCHAR(255) NOT NULL,
    city       VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL
);

CREATE TABLE seat (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id    BIGINT      NOT NULL REFERENCES venue (id),
    row_label   VARCHAR(10) NOT NULL,
    seat_number INT         NOT NULL,
    CONSTRAINT uq_seat_venue_row_number UNIQUE (venue_id, row_label, seat_number)
);

CREATE TABLE category (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uq_category_name UNIQUE (name)
);

CREATE TABLE event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255)  NOT NULL,
    description TEXT,
    venue_id    BIGINT        NOT NULL REFERENCES venue (id),
    start_time  TIMESTAMPTZ   NOT NULL,
    end_time    TIMESTAMPTZ   NOT NULL,
    base_price  NUMERIC(12, 2) NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_event_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED')),
    CONSTRAINT ck_event_time CHECK (end_time > start_time)
);

CREATE TABLE event_category (
    event_id    BIGINT NOT NULL REFERENCES event (id),
    category_id BIGINT NOT NULL REFERENCES category (id),
    PRIMARY KEY (event_id, category_id)
);

CREATE INDEX idx_event_venue_id ON event (venue_id);
